"""Figure for Phase 2 item 1's residual triple: does the residual decorrelate,
and does the sampling split decide it?

Left panel  -- the noise-proxy band (above the official band's upper edge):
               the band the original reasoning called a noise proxy.  Three
               splits, same estimator, only the frame grouping differs.
Right panel -- the band the pair actually averages over (the proportional
               retained band), the same way.  This is the number that decides
               whether (D_A, D_B) can work.

Both panels are needed together: the left one says the noise proxy is not
white under contiguous sampling and is white under interleaving, and the right
one says the same thing about the band the pair really uses.  A single panel
would look like a band choice; the pair of them shows it is a sampling choice.

An image looking right is not the acceptance criterion -- the numbers behind it
are in reports/phase2_noise_autocorrelation.md, and both are regenerated by
scripts/phase2_summarize.py.
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

RESIDUAL = Path("data/processed/crossfit/phase2_residual_proxy.json")
AUTOCORR = Path("data/processed/crossfit/phase2_autocorr.json")
OUT = Path("reports/figures/phase2_residual_decay.png")

SPLIT_STYLE = {
    "sa64_cont3": dict(color="C3", ls="--", marker="s", label="contiguous blocks (SA64)"),
    "sa64_int3": dict(color="C0", ls="-", marker="o", label="interleaved p=3 (SA64)"),
    "sa64_int5": dict(color="C2", ls="-", marker="^", label="interleaved p=5 (SA64)"),
    "hsa64_int3": dict(color="0.45", ls=":", marker="D", label="interleaved p=3 (HSA64)"),
}


def mean(xs):
    xs = list(xs)
    return sum(xs) / len(xs) if xs else None


def draw(ax, get, title, ylabel):
    """Plot mean r(lag) per split, with the null band drawn as a grey ribbon."""
    all_null = []
    for split, style in SPLIT_STYLE.items():
        lags, rs, nuls = get(split)
        if not lags:
            continue
        all_null += nuls
        ax.plot(lags, rs, ms=5, lw=1.7, **style)
    if all_null:
        n = float(np.mean(all_null))
        ax.fill_between([0.7, 40], -n, n, color="0.85", zorder=0,
                        label=r"empirical null $\pm$ scale")
    ax.axhline(0, color="0.6", lw=0.8)
    ax.set_xscale("log")
    ax.set_xlim(0.7, 40)
    ax.set_ylim(-0.35, 1.05)
    ax.set_xlabel("physical frame lag $\\ell$ (log)")
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7.5, loc="upper right")


def residual_decay(split):
    doc = json.loads(RESIDUAL.read_text())
    for seq in doc:
        folds = [f for f in doc[seq]["whole_volume"]["folds"] if f["split"] == split]
        if not folds:
            continue
        rows = [f["rules"]["proportional"]["proxy"] for f in folds
                if f["rules"]["proportional"]["proxy"].get("status") == "OK"]
        lags = sorted({int(L) for r in rows for L in r["autocorr_A"]})
        rs = [mean([r["autocorr_A"][str(L)]["r"] for r in rows
                    if str(L) in r["autocorr_A"]]) for L in lags]
        ns = [mean([r["autocorr_A"][str(L)]["null"] for r in rows
                    if str(L) in r["autocorr_A"]]) for L in lags]
        return lags, rs, ns
    return [], [], []


def retained_decay(split):
    doc = json.loads(AUTOCORR.read_text())
    for seq in doc:
        folds = [f for f in doc[seq]["folds"] if f["split"] == split]
        if not folds:
            continue
        lags = sorted({int(L) for f in folds
                       for L in f["rules"]["proportional"]["power"]["autocorr_A"]["lags"]})
        rs, ns = [], []
        for L in lags:
            vals = [f["rules"]["proportional"]["power"]["autocorr_A"]["lags"][str(L)]
                    for f in folds
                    if str(L) in f["rules"]["proportional"]["power"]["autocorr_A"]["lags"]]
            rs.append(mean([v["r"] for v in vals]))
            ns.append(mean([v["null"] for v in vals]))
        return lags, rs, ns
    return [], [], []


def main():
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13.5, 5.0))

    draw(ax1, residual_decay,
         "The band ABOVE the official band\n(what the old reasoning called a noise proxy)",
         "autocorrelation of per-frame band power")
    draw(ax2, retained_decay,
         "The band the pair actually averages over\n(proportional retained band)",
         "autocorrelation of per-frame band power")

    ax1.text(0.02, 0.03,
             "same estimator, same sequence, only the\nframe grouping differs",
             transform=ax1.transAxes, fontsize=8, style="italic", color="0.3")

    fig.suptitle("Phase 2 item 1: whether the residual is white is decided by the split, "
                 "not by the band", fontsize=12)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT, dpi=150)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
